import {readFileSync,writeFileSync} from 'node:fs'
const source=new URL('../../../runtime/src/news/sources.json',import.meta.url)
const output=new URL('../lib/personal/local_news_sources.g.dart',import.meta.url)
const rows=JSON.parse(readFileSync(source,'utf8'))
const quote=text=>"'"+text.replaceAll('\\','\\\\').replaceAll("'","\\'").replaceAll('$','\\$')+"'"
const content="// Generated by tool/generate_news_sources.mjs from runtime/src/news/sources.json.\n// Do not edit; run the generator after changing the shared resource.\npart of 'local_news.dart';\n\nconst publicNewsSources = [\n"+rows.map(s=>`  NewsSource(${[s.id,s.name,s.url,s.language].map(quote).join(', ')}),`).join('\n')+'\n];\n'
if(process.argv.includes('--check')){
 if(readFileSync(output,'utf8')!==content)throw Error('News sources drifted; run node clients/flutter/tool/generate_news_sources.mjs')
}else writeFileSync(output,content)
